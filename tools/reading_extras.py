#!/usr/bin/env python3
"""Rebuild this book's Traditional Chinese index, combined reader and legacy links.

Run after studio build --zh-tw. All current translations must match their metadata.
This book-specific adapter does not modify the shared toolkit or translated units.
"""
from pathlib import Path
import argparse,json,re,sys
from studio_lib.common import load_yaml,atomic_write,safe_path,StudioError
from studio_lib.builder import sha,translated_text,rewritten_body,relative_url,translation_status


def build(root,check=False):
    book=load_yaml(root/'book.yaml')
    states=translation_status(root,book)
    # Status can be pending human review, but must be based on current source bytes.
    if any(x['status'] not in ('review_pending','current') for x in states):
        raise StudioError('先生成与当前源稿匹配的繁体转换稿：'+str(states))
    entries=load_yaml(root/'translations.yaml')['entries']
    by_id={e['unit']:e for e in entries if e['language']=='zh-TW'}
    units=[dict(u,path=by_id[u['id']]['path']) for u in book['units']]
    bodies={u['id']:safe_path(root,u['path']).read_text() for u in units}
    for u in units:
        if sha(bodies[u['id']])!=by_id[u['id']]['output_sha256']:
            raise StudioError('译文存在未登记修改：'+u['path'])
    terms=book.get('protected_terms',[])
    conv=lambda t:translated_text(t,terms)
    title=conv(book['title']);date=book['baseline']['checked_on']
    notice='資料核對截至 '+date+'。本版為本地修訂候選；繁體由已保存的簡體源稿轉換，語言審讀待完成。\n'
    toc='\n'.join('- [{}]({})'.format(conv(u['title']),relative_url(root/u['path'],root/'zh-TW')) for u in units)
    readme='# '+title+'\n\n'+notice+'\n[連續閱讀](全書.md) · [简体入口](../README.md) · [版本與核驗說明](../docs/版本与核验说明.md)\n\n## 目錄\n\n'+toc+'\n\n四月 PDF 是歷史版本，未包含本次修訂。\n'
    chunks=['<!-- Generated by tools/reading_extras.py; edit Chinese source units instead. -->','# '+title,notice,'## 目錄','\n'.join('- [{}](#{})'.format(conv(u['title']),u['id']) for u in units)]
    for u in units:
        body=re.sub(r'<a id="([^"]+)"></a>',lambda m:'<a id="'+u['id']+'-'+m.group(1)+'"></a>',bodies[u['id']])
        chunks+=['<a id="'+u['id']+'"></a>',rewritten_body(root,u,body,root/'zh-TW',units)]
    combined='\n\n'.join(chunks)+'\n'
    seen=set()
    def dedup(m):
        k=m.group(1)
        if k in seen:return ''
        seen.add(k);return m.group(0)
    combined=re.sub(r'<a id="([^"]+)"></a>',dedup,combined)
    outputs={'zh-TW/README.md':readme,'zh-TW/全書.md':combined}
    aliases=load_yaml(root/'legacy-reading-paths.yaml')
    for item in aliases:
        path=item['path'];target=by_id[item['unit']]['path']
        if path==target:continue
        if path in outputs or path in {u['path'] for u in units}:raise StudioError('旧入口与正文冲突：'+path)
        outputs[path]='# 舊版閱讀入口\n\n章節網址保留，內容已更新。請繼續閱讀[本章九月修訂稿]('+relative_url(root/target,(root/path).parent)+')。\n'
    manifest_path=root/'.studio/reading-extras.json'
    previous=json.loads(manifest_path.read_text()) if manifest_path.exists() else {'files':{}}
    changed=[p for p,t in outputs.items() if not safe_path(root,p).exists() or safe_path(root,p).read_text()!=t]
    for p in changed:
        target=safe_path(root,p)
        if target.exists() and previous['files'].get(p)!=sha(target.read_bytes()):
            raise StudioError('派生阅读文件存在人工修改或未接管：'+p)
    manifest=json.dumps({'version':1,'files':{p:sha(t) for p,t in outputs.items()}},ensure_ascii=False,sort_keys=True,indent=2)+'\n'
    if not manifest_path.exists() or manifest_path.read_text()!=manifest:changed.append('.studio/reading-extras.json')
    if not check:
        for p,t in outputs.items():atomic_write(safe_path(root,p),t)
        atomic_write(manifest_path,manifest)
    return {'ok':not changed if check else True,'changed':changed,'units':len(units),'aliases':len(aliases),'review':'pending'}

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    try:
        result=build(Path(__file__).resolve().parent.parent,args.check)
        print(json.dumps(result,ensure_ascii=False));sys.exit(0 if result['ok'] else 1)
    except (StudioError,ValueError,KeyError) as exc:
        print(str(exc),file=sys.stderr);sys.exit(1)
